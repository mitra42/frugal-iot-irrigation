"""Readable schematic for the generic ESP32 I/O board, drawn with schlib
(Diode663/kicad-claude-skills, MIT). circuit.py is the source of truth for
parts and nets; this file only decides where things are drawn.

    <KiCad python> draw.py [--lint-only]
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from schlib import Design
import dbase, dblk1, dblk2, dblk3, dblk4

PROJ = os.path.normpath(os.path.join(HERE, '..', '..', 'esp32_io_board'))

def main():
    d = Design(PROJ, 'esp32_io_board', title='Frugal-IoT Irrigation', rev='0.1',
               company='Natural Innovation')
    parts = {r: (p['lib'], p['value'], p['props']['Footprint'], p['props']) for r, p in dbase.PARTS.items()}
    d.lint(parts, dbase.NETS, dbase.NO_CONNECT)
    if '--lint-only' in sys.argv:
        return
    s = d.sheet('esp32_io_board.kicad_sch', 'Frugal-IoT Irrigation V0.1', paper='auto',
                comment='Generated by claude-tools/schematic/draw.py from circuit.py -- edit those, not this file')
    dbase.S = s
    dblk1.usb(101.6, 101.6)
    dblk1.v12(406.4, 101.6)
    dblk2.charger(812.8, 121.92)
    dblk2.syspwr(1219.2, 101.6)
    dblk3.module(162.56, 609.6)
    dblk3.ports(609.6, 609.6)
    dblk4.rs485(1016, 609.6)
    dblk4.relays(1422.4, 609.6)
    s.arrange()
    d.write(force=True, strict=('--strict' in sys.argv))
    ok = d.verify(dbase.NETS, dbase.NO_CONNECT)
    d.erc()
    d.check_text()
    print('VERIFY', 'OK' if ok else 'FAIL')

if __name__ == '__main__':
    main()
